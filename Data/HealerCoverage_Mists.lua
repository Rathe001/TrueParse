-- theirs to heal, times healer count) with anchors fitted to MISTS captures.
--
-- WHY MISTS GETS ITS OWN QUARTILES instead of borrowing retail's: measured
-- 2026-08-27 with scripts/fit-healer-coverage.lua over both clients' real
-- SavedVariables, the populations genuinely differ -
--   retail  (n=240)  p25 0.410  p50 0.798  p75 1.001
