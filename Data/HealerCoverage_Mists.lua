-- 0.414/0.782/1.001 is what validates the fit script itself.)
--
-- Until this file existed, Mists five-man healers were scored on HPS against
-- pooled RAID curves and then hit the low-demand floor on every clean pull -
-- which read as "pinned at exactly 75, most dungeons" (Josh 2026-08-27).
-- The Scarlet Halls run in Engine.lua's comment (healers scoring 0.0-90.0 on
-- consecutive pulls) is the same failure before the floor papered over it.
--
-- Loading this also activates Engine's healer-damage drop for Mists five-mans
-- (both gate on HEALER_COVERAGE_UNIT): healer damage becomes context instead
-- of 21% of the grade. That is the intended pairing - "never remove a metric
-- before its replacement is in place" - and the replacement is now in place.
--
-- Bootstrap caveats are the retail file's, unchanged: one player's groups,
-- median 50 by construction against its own fitting population, re-fit when
-- a broader sample exists (scripts/fit-healer-coverage.lua <SV path...>).
